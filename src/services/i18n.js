export function getLanguage() {
  try {
    return localStorage.getItem(LANGUAGE_KEY) === 'hi' ? 'hi' : 'en';
  } catch {
    return 'en';
  }
}

export function setLanguage(language) {
  const next = language === 'hi' ? 'hi' : 'en';
  try {
    localStorage.setItem(LANGUAGE_KEY, next);
  } catch {
    // Ignore storage failures and keep the in-memory selection in the current page.
  }
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('local-language-change', { detail: { language: next } }));
  }
  return next;
}

export function tr(value, language = getLanguage()) {
  if (language !== 'hi') return value;
  return HINDI[value] ?? value;
}

export function toggleLanguage(language) {
  return setLanguage(language === 'hi' ? 'en' : 'hi');
}
